  function rnd(n) { return 1 + Math.floor(Math.random() * n); }
  function parse(expr) { // '2d4+2' → {n, s, b}
    const m = /^(\d+)d(\d+)([+-]\d+)?$/.exec(String(expr).replace(/\s|к/g, (c) => (c === 'к' ? 'd' : '')));
    return m ? { n: +m[1], s: +m[2], b: +(m[3] || 0) } : { n: 0, s: 0, b: +expr || 0 };
  }
  function roll(expr, crit) {
    const p = parse(expr), r = [];
    const n = crit ? p.n * 2 : p.n;
    for (let i = 0; i < n; i++) r.push(rnd(p.s));
    return { r, b: p.b, t: r.reduce((a, b) => a + b, 0) + p.b, e: expr };
  }
  function d20(adv) { // adv: 1 перевага, -1 перешкода
    const a = rnd(20); if (!adv) return { d: [a], v: a };
    const b = rnd(20); return { d: [a, b], v: adv > 0 ? Math.max(a, b) : Math.min(a, b) };
  }

